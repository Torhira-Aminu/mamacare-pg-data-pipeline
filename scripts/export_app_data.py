"""Export the verified Athena ZIP summary as app-integration/zip_summary.js.

Source: docs/evidence/athena_results_*.json (real Athena output for sql/02_zip_summary.sql).
Output is a .js file that sets a global, so the static app works even when opened
straight from disk (browsers block fetch() of local JSON files on file:// pages).

    python scripts/export_app_data.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
TYPE_LABELS = {
    "prenatal_clinics": "Prenatal clinics", "wic_locations": "WIC locations",
    "medicaid_resources": "Medicaid help", "food_pantries": "Food pantries",
    "diaper_banks": "Diaper banks", "childcare_providers": "Childcare providers",
    "transportation_assistance": "Transportation help", "mental_health_services": "Mental health services",
}


def build():
    evidence_file = sorted((ROOT / "docs" / "evidence").glob("athena_results_*.json"))[-1]
    ev = json.loads(evidence_file.read_text())
    q = ev["queries"]["02_zip_summary"]
    header = q["header"]
    zips = {}
    for row in q["rows"]:
        r = dict(zip(header, row))
        zips[r["zip_code"]] = {
            "city": r["city"],
            "total": int(r["total_resources"]),
            "by_type": {t: int(r[t]) for t in TYPE_LABELS},
        }
    return {
        "synthetic": True,
        "notice": "Synthetic demo data generated for a portfolio project. Not real service availability.",
        "source": f"Amazon Athena query sql/02_zip_summary.sql, captured {ev['captured_at_utc']}",
        "type_labels": TYPE_LABELS,
        "zips": zips,
    }


if __name__ == "__main__":
    data = build()
    out = ROOT / "app-integration" / "zip_summary.js"
    out.write_text("// Generated by scripts/export_app_data.py. SYNTHETIC DATA.\n"
                   "window.MAMACARE_ZIP_SUMMARY = " + json.dumps(data, indent=1) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(data['zips'])} ZIPs)")
